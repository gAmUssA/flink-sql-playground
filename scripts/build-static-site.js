#!/usr/bin/env node
/*
 * Builds the static frontend for hosting apart from the backend (GitHub Pages).
 *
 * Usage: node scripts/build-static-site.js <out-dir> <base-path> <api-origin>
 *   out-dir     directory to create; must not exist
 *   base-path   URL path the site is served under, e.g. /flink-sql-playground/
 *   api-origin  backend origin, e.g. https://flink-sql-playground-production.up.railway.app
 *
 * Copies src/main/resources/META-INF/resources, which must already hold the editor bundle
 * (node scripts/build-editor.js), then:
 *   - sets <base href> to base-path so assets and share links resolve under it
 *   - writes js/config.js with window.API_BASE = api-origin
 *   - adds the backend CSP from application.properties as a <meta> tag (a static host
 *     sends no headers), with api-origin added to connect-src and frame-ancestors removed
 *     (browsers ignore it in <meta>)
 *   - copies index.html to 404.html so /f/<code> links fall back to the app
 *
 * Stdout: one JSON object {outDir, basePath, apiOrigin, files}. Exit 1 with a message on stderr on failure.
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO = path.resolve(__dirname, '..');
const SOURCE = path.join(REPO, 'src/main/resources/META-INF/resources');
const PROPERTIES = path.join(REPO, 'src/main/resources/application.properties');
const CSP_KEY = 'quarkus.http.header."Content-Security-Policy".value=';
const BASE_TAG = '<base href="/" />';
const EDITOR_BUNDLE = 'js/editor.bundle.js';

function readCsp(propertiesText) {
  const line = propertiesText.split('\n').find((l) => l.startsWith(CSP_KEY));
  if (!line) throw new Error(`No ${CSP_KEY} line in application.properties`);
  return line.slice(CSP_KEY.length).trim();
}

/** Returns the CSP for a <meta> tag: api origin in connect-src, frame-ancestors removed. */
function metaCsp(headerCsp, apiOrigin) {
  const directives = headerCsp.split(';').map((d) => d.trim()).filter(Boolean)
    .filter((d) => !d.startsWith('frame-ancestors'))
    .map((d) => (d.startsWith('connect-src') ? `${d} ${apiOrigin}` : d));
  if (!directives.some((d) => d.startsWith('connect-src'))) directives.push(`connect-src 'self' ${apiOrigin}`);
  return directives.join('; ');
}

function validateArgs(basePath, apiOrigin) {
  if (!/^\/([A-Za-z0-9._~-]+\/)*$/.test(basePath)) {
    throw new Error(`base-path must start and end with "/", e.g. /flink-sql-playground/ (got ${basePath})`);
  }
  let url;
  try { url = new URL(apiOrigin); } catch (e) { throw new Error(`api-origin is not a URL: ${apiOrigin}`); }
  if (url.protocol !== 'https:' || url.origin !== apiOrigin) {
    throw new Error(`api-origin must be a bare https origin like https://example.com (got ${apiOrigin})`);
  }
}

function transformIndex(html, basePath, csp) {
  if (!html.includes(BASE_TAG)) throw new Error(`index.html has no ${BASE_TAG} to rewrite`);
  const escaped = csp.replace(/"/g, '&quot;');
  return html.replace(BASE_TAG,
    `<base href="${basePath}" />\n    <meta http-equiv="Content-Security-Policy" content="${escaped}" />\n` +
    '    <meta name="referrer" content="strict-origin-when-cross-origin" />');
}

function build(outDir, basePath, apiOrigin, source = SOURCE) {
  validateArgs(basePath, apiOrigin);
  if (fs.existsSync(outDir)) throw new Error(`out-dir already exists: ${outDir}`);
  if (!fs.existsSync(path.join(source, EDITOR_BUNDLE))) {
    throw new Error(`${EDITOR_BUNDLE} is missing — run \`npm ci --omit=dev && node scripts/build-editor.js\` first`);
  }
  fs.cpSync(source, outDir, { recursive: true });

  const csp = metaCsp(readCsp(fs.readFileSync(PROPERTIES, 'utf8')), apiOrigin);
  const index = transformIndex(fs.readFileSync(path.join(outDir, 'index.html'), 'utf8'), basePath, csp);
  fs.writeFileSync(path.join(outDir, 'index.html'), index);
  fs.writeFileSync(path.join(outDir, '404.html'), index);
  fs.writeFileSync(path.join(outDir, 'js/config.js'),
    `// Generated by scripts/build-static-site.js for the static site.\nwindow.API_BASE = ${JSON.stringify(apiOrigin)};\n`);

  const files = [];
  const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).forEach((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else files.push(path.relative(outDir, p));
  });
  walk(outDir);
  return { outDir, basePath, apiOrigin, files: files.sort() };
}

if (require.main === module) {
  const [outDir, basePath, apiOrigin] = process.argv.slice(2);
  if (!outDir || !basePath || !apiOrigin) {
    console.error('usage: node scripts/build-static-site.js <out-dir> <base-path> <api-origin>');
    process.exit(1);
  }
  try {
    console.log(JSON.stringify(build(path.resolve(outDir), basePath, apiOrigin)));
  } catch (e) {
    console.error(`build-static-site: ${e.message}`);
    process.exit(1);
  }
}

module.exports = { build, metaCsp, readCsp, transformIndex, validateArgs };
